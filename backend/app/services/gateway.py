"""nginx gateway rules for approved remediation actions.

Two files are written into `settings.gateway_rules_dir`:

  zombieshield.conf             `location` blocks, included in the gateway's `server {}`
  http/zombieshield-maps.conf   `map` and `limit_req_zone` definitions, included in `http {}`

Only actions in status APPLIED or VERIFIED are rendered, so nothing reaches the gateway without an
administrator approving and then applying it. Rules are method-specific: one `location` per path
(nginx uses the first matching regex location), with per-method behaviour selected through `map`
variables, because `limit_req` and `add_header` cannot sit inside `if`.

Rule kinds
  BLOCK_ROUTE          return 410 Gone for the retired method + path
  REQUIRE_AUTH         return 401 when the request carries no credentials (`$zs_has_auth` = "0")
  RATE_LIMIT           per-client `limit_req` at a rate derived from normal traffic, 429 when exceeded
  DEPRECATION_HEADERS  add `Deprecation` / `Sunset` / successor `Link` headers (RFC 9745, RFC 8594)
"""

import os
import re
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

from app.core.config import get_settings

RENDERED_STATES = ("APPLIED", "VERIFIED")
LOCATIONS_FILE = "zombieshield.conf"
MAPS_FILE = os.path.join("http", "zombieshield-maps.conf")
_SAFE_SEGMENT = re.compile(r"^[A-Za-z0-9._~!@:+,=-]*$")
_SAFE_VALUE = re.compile(r"^[A-Za-z0-9 ._:/,;=<>\"-]*$")
_HEADER = "# Generated by ZombieShield remediation. Do not edit: changes are overwritten when rules are applied or rolled back.\n"


class UnsafeRule(ValueError):
    """The rule cannot be expressed safely in nginx syntax."""


def path_regex(endpoint_path: str) -> str:
    """Canonical template -> anchored nginx regex. `{id}` matches one segment, a trailing `*` a prefix."""
    prefix = endpoint_path.endswith("*")
    path = endpoint_path[:-1] if prefix else endpoint_path
    if not path.startswith("/"):
        raise UnsafeRule(f"path must start with '/': {endpoint_path!r}")
    parts = []
    for segment in path.split("/")[1:]:
        if segment == "{id}":
            parts.append("[^/]+")
        elif _SAFE_SEGMENT.match(segment):
            parts.append(re.escape(segment))
        else:
            raise UnsafeRule(f"unsupported characters in path segment {segment!r}")
    body = "/" + "/".join(parts)
    if prefix:
        return "^" + body + ".*$"
    return "^" + body.rstrip("/") + "/?$"


def _method(method: str) -> str:
    method = method.upper()
    if not re.fullmatch(r"[A-Z]{3,10}", method):
        raise UnsafeRule(f"invalid HTTP method {method!r}")
    return method


def _value(text: str) -> str:
    if not _SAFE_VALUE.match(text) or '"' in text:
        raise UnsafeRule(f"unsafe header value {text!r}")
    return text


@dataclass
class RenderableRule:
    id: str
    kind: str
    host: str
    method: str
    path: str
    params: dict
    title: str


def _group(rules: list[RenderableRule]) -> dict[str, list[RenderableRule]]:
    grouped: dict[str, list[RenderableRule]] = defaultdict(list)
    for rule in rules:
        grouped[path_regex(rule.path)].append(rule)
    return dict(sorted(grouped.items()))


def render(rules: list[RenderableRule], *, upstream: str | None = None, auth_variable: str | None = None) -> tuple[str, str]:
    """Return (locations_conf, maps_conf) for the given rules."""
    settings = get_settings()
    upstream = upstream or settings.gateway_upstream
    auth_variable = auth_variable or settings.gateway_auth_variable
    if not re.fullmatch(r"https?://[A-Za-z0-9._:-]+(/[A-Za-z0-9._/-]*)?", upstream):
        raise UnsafeRule(f"invalid upstream {upstream!r}")
    if not re.fullmatch(r"\$[A-Za-z_][A-Za-z0-9_]*", auth_variable):
        raise UnsafeRule(f"invalid auth variable {auth_variable!r}")
    locations, maps = [_HEADER], [_HEADER]
    for n, (regex, group) in enumerate(_group(rules).items(), start=1):
        body: list[str] = []
        by_kind: dict[str, list[RenderableRule]] = defaultdict(list)
        for rule in group:
            by_kind[rule.kind].append(rule)
        if "BLOCK_ROUTE" in by_kind:
            methods = sorted({_method(r.method) for r in by_kind["BLOCK_ROUTE"]})
            maps.append(f"map $request_method $zs_block_{n} {{\n" + "".join(f"    {m} 1;\n" for m in methods) + "    default 0;\n}\n")
            body.append(f"    if ($zs_block_{n}) {{ return 410; }}")
        if "REQUIRE_AUTH" in by_kind:
            methods = sorted({_method(r.method) for r in by_kind["REQUIRE_AUTH"]})
            maps.append(f'map "$request_method:{auth_variable}" $zs_noauth_{n} {{\n' + "".join(f'    "{m}:0" 1;\n' for m in methods) + "    default 0;\n}\n")
            body.append(f"    if ($zs_noauth_{n}) {{ return 401; }}")
        for m_index, rule in enumerate(sorted(by_kind.get("RATE_LIMIT", []), key=lambda r: r.method), start=1):
            method = _method(rule.method)
            rate, burst = int(rule.params.get("rate_per_minute", 60)), int(rule.params.get("burst", 10))
            if not (1 <= rate <= 100000 and 0 <= burst <= 100000):
                raise UnsafeRule(f"rate limit out of range: {rate}r/m burst {burst}")
            key, zone = f"$zs_rl_key_{n}_{m_index}", f"zs_rl_{n}_{m_index}"
            maps.append(f'map $request_method {key} {{\n    {method} $binary_remote_addr;\n    default "";\n}}\n'
                        f"limit_req_zone {key} zone={zone}:10m rate={rate}r/m;\n")
            body.append(f"    limit_req zone={zone} burst={burst} nodelay;")
        if "RATE_LIMIT" in by_kind:
            body.append("    limit_req_status 429;")
        if "DEPRECATION_HEADERS" in by_kind:
            headers: dict[str, dict[str, str]] = {"Deprecation": {}, "Sunset": {}, "Link": {}}
            for rule in by_kind["DEPRECATION_HEADERS"]:
                method = _method(rule.method)
                headers["Deprecation"][method] = _value(rule.params.get("deprecation", "true"))
                if rule.params.get("sunset"):
                    headers["Sunset"][method] = _value(rule.params["sunset"])
                if rule.params.get("successor"):
                    headers["Link"][method] = _value(f'<{rule.params["successor"]}>; rel=successor-version')
            for name, values in headers.items():
                if not values:
                    continue
                var = f"$zs_{name.lower()}_{n}"
                maps.append(f"map $request_method {var} {{\n" + "".join(f"    {m} '{v}';\n" for m, v in sorted(values.items())) + '    default "";\n}\n')
                body.append(f"    add_header {name} {var} always;")
        titles = "".join(f"# - [{r.kind}] {r.method} {r.path} ({r.host}) action {r.id}\n" for r in group)
        locations.append(f"{titles}location ~ \"{regex}\" {{\n" + "\n".join(body) + "\n"
                         f"    proxy_pass {upstream};\n    proxy_set_header Host $host;\n"
                         "    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n}\n")
    return "\n".join(locations), "\n".join(maps)


def host_allowed(host: str) -> bool:
    allowed = [h.strip().lower() for h in get_settings().gateway_hosts.split(",") if h.strip()]
    return not allowed or host.lower() in allowed


def write(rules: list[RenderableRule], directory: str | None = None) -> dict:
    """Atomically replace both rule files. Returns the paths and how many rules were rendered."""
    target = Path(directory or get_settings().gateway_rules_dir)
    rendered = [rule for rule in rules if host_allowed(rule.host)]
    locations, maps = render(rendered)
    written = []
    for name, content in ((LOCATIONS_FILE, locations), (MAPS_FILE, maps)):
        path = target / name
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + ".tmp")
        tmp.write_text(content)
        os.replace(tmp, path)
        written.append(str(path))
    return {"files": written, "rules": len(rendered), "skipped_other_hosts": len(rules) - len(rendered)}
